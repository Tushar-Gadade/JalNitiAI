"""Data layer.

Real data first, clearly-labelled synthetic fallback second.
  * data/raw/reservoir_real.csv  (optional) columns: date, storage_mcm [, inflow_mcm]
        -> from India-WRIS / CWC weekly bulletins / a Kaggle reservoir dataset (see README)
  * data/raw/weather_real.csv    (optional) columns: date, temp_c, rain_mm   (IMD / Kaggle)
  * data/raw/demand_real.csv     (optional) columns: date, zone_id, demand_mld (CMWSSB / Metrowater meter data)
Anything missing is generated by `generate_synthetic()` with a fixed seed and rule-based generators.
Synthetic demand must NOT be reported as real-world forecasting accuracy.
"""
import numpy as np
import pandas as pd
from .config import PROCESSED, RAW, ZONES, RESERVOIR

START, END = "2022-01-01", "2026-10-05"


def _holidays(idx):
    fixed = {(1, 26), (5, 1), (8, 15), (10, 2), (5, 1), (12, 25)}
    return np.array([(d.month, d.day) in fixed for d in idx])


def generate_synthetic(seed=7):
    rng = np.random.default_rng(seed)
    idx = pd.date_range(START, END, freq="D")
    doy = np.asarray(idx.dayofyear)
    # Chennai: the north-east (retreating) monsoon, Oct-Dec, delivers most of the rain; the south-west monsoon (Jun-Sep) is minor.
    ne = np.asarray((idx.month >= 10) & (idx.month <= 12))
    sw = np.asarray((idx.month >= 6) & (idx.month <= 9))
    monsoon = ne | sw
    temp = 29 + 4 * np.sin(2 * np.pi * (doy - 54) / 365) - 2 * ne + rng.normal(0, 1.0, len(idx))   # peak late May, coolest Jan
    rain_p = np.where(ne, 0.5, np.where(sw, 0.25, 0.04))
    rain = rng.gamma(1.4, np.where(ne, 16.0, np.where(sw, 7.0, 5.0))) * (rng.random(len(idx)) < rain_p)
    rain = np.where(idx.year == 2026, rain * 0.5, rain)           # weak monsoon year for demo (2026 storage is low before the NE monsoon)
    weather = pd.DataFrame({"date": idx, "temp_c": temp.round(1), "rain_mm": rain.round(1)})

    # Reservoir (complex-level, MCM) via simple water balance on lagged catchment rainfall
    cap = RESERVOIR["capacity_mcm"]
    inflow, storage, s = [], [], 200.0
    rain_lag = pd.Series(rain).rolling(3, min_periods=1).mean().values
    for t in range(len(idx)):
        inf = 0.0 if rain_lag[t] < 1 else 0.7 * rain_lag[t] ** 1.15 * (1.0 if ne[t] else 0.6 if sw[t] else 0.3)
        out = 1.0 + 0.04 * max(temp[t] - 29, 0)                     # city + evaporation draw (MCM/day)
        s = float(np.clip(s + inf - out, 20.0, cap))
        inflow.append(inf); storage.append(s)
    reservoir = pd.DataFrame({"date": idx, "storage_mcm": np.round(storage, 2),
                              "inflow_mcm": np.round(inflow, 3), "source": "synthetic", "quality_flag": "SIMULATED"})

    rows = []
    dow = np.asarray(idx.dayofweek)
    hol = _holidays(idx)
    for z in ZONES:
        base = z["base_mld"]
        season = 1 + 0.08 * np.sin(2 * np.pi * (doy - 70) / 365)
        heat = 1 + 0.012 * (temp - 29)
        if z["type"] == "residential":
            week = np.where(dow >= 5, 1.04, 1.0)
        elif z["type"] == "hospital":
            week = np.ones(len(idx))
        else:
            week = np.where(dow >= 5, 0.75, 1.0) * np.where(hol, 0.7, 1.0)
        noise = rng.lognormal(0, 0.025 if z["type"] != "industry_nonessential" else 0.05, len(idx))
        d = base * season * heat * week * noise * (1 + 0.01 * (z["id"] % 3 - 1))
        rows.append(pd.DataFrame({"date": idx, "zone_id": z["id"], "demand_mld": d.round(2)}))
    demand = pd.concat(rows, ignore_index=True)
    return weather, reservoir, demand


def build_all(force=False):
    PROCESSED.mkdir(parents=True, exist_ok=True)
    paths = {k: PROCESSED / f"{k}.csv" for k in ("weather", "reservoir", "demand")}
    if all(p.exists() for p in paths.values()) and not force:
        return
    w, r, d = generate_synthetic()
    real_w, real_r, real_d = RAW / "weather_real.csv", RAW / "reservoir_real.csv", RAW / "demand_real.csv"
    if real_w.exists():
        w = pd.read_csv(real_w, parse_dates=["date"])
    if real_r.exists():
        rr = pd.read_csv(real_r, parse_dates=["date"]).sort_values("date")
        if "inflow_mcm" not in rr:
            rr["inflow_mcm"] = rr["storage_mcm"].diff().clip(lower=0).fillna(0)
        rr["source"], rr["quality_flag"] = "real", "OK"
        r = rr.set_index("date").resample("D").interpolate().reset_index()
        r["source"], r["quality_flag"] = "real", "INTERPOLATED"
    if real_d.exists():
        d = pd.read_csv(real_d, parse_dates=["date"])
    w.to_csv(paths["weather"], index=False); r.to_csv(paths["reservoir"], index=False); d.to_csv(paths["demand"], index=False)


def load(name):
    build_all()
    return pd.read_csv(PROCESSED / f"{name}.csv", parse_dates=["date"])
